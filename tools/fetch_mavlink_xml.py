#!/usr/bin/env python3
"""Write tools/mavlink-xml/common-excerpt.xml from the official MAVLink
message definitions, pinned to one commit of github.com/mavlink/mavlink.

The inspector decodes the payload of six common messages. Their definitions
(and the enums their fields refer to) are copied out of common.xml and the
files it includes (standard.xml, minimal.xml), so the repository does not
carry 740 kB of XML. Downloads are checked against the SHA-256 below.

Run once, when the pin changes (needs network):
    python3 tools/fetch_mavlink_xml.py
Then regenerate docs/js/msgdefs.js with tools/gen_web_defs.py, which checks
the excerpt against pymavlink.
"""
import hashlib
import os
import sys
import urllib.request
import xml.etree.ElementTree as ET

COMMIT = "12c898d88ce18d24e8caf6338596e98c5005bc97"
URL = "https://raw.githubusercontent.com/mavlink/mavlink/%s/message_definitions/v1.0/%s"
FILES = {
    "common.xml": "a4ac8a1144529195af6f948e5b4429bae0bd7b8650472d0ce09fbc5ca7bde7d6",
    "standard.xml": "0c08a5be4a858910ac02111a51551e0b8fa2088675a5ca0a48dfd7792fa94018",
    "minimal.xml": "7b1e79a1cadedb618042a3f78c09a76ef1f7440df71fa179e647001eeab7475b",
}
MESSAGES = ["HEARTBEAT", "SYS_STATUS", "GPS_RAW_INT", "ATTITUDE", "GLOBAL_POSITION_INT", "VFR_HUD"]
ENUMS = ["MAV_TYPE", "MAV_AUTOPILOT", "MAV_MODE_FLAG", "MAV_STATE", "GPS_FIX_TYPE"]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "mavlink-xml", "common-excerpt.xml")


def fetch(name):
    with urllib.request.urlopen(URL % (COMMIT, name), timeout=60) as r:
        data = r.read()
    got = hashlib.sha256(data).hexdigest()
    if got != FILES[name]:
        sys.exit("%s: sha256 %s, expected %s" % (name, got, FILES[name]))
    return ET.fromstring(data)


def main():
    messages, enums = {}, {}
    for name in FILES:
        root = fetch(name)
        for m in root.iter("message"):
            if m.get("name") in MESSAGES:
                messages[m.get("name")] = m
        for e in root.iter("enum"):
            if e.get("name") in ENUMS:
                enums[e.get("name")] = e
    missing = [n for n in MESSAGES if n not in messages] + [n for n in ENUMS if n not in enums]
    if missing:
        sys.exit("not found: %s" % ", ".join(missing))

    out = ET.Element("mavlink")
    out.text = "\n  "
    e_parent = ET.SubElement(out, "enums")
    for n in ENUMS:
        e_parent.append(enums[n])
    m_parent = ET.SubElement(out, "messages")
    for n in MESSAGES:
        m_parent.append(messages[n])
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0"?>\n')
        f.write("<!-- Excerpt of the official MAVLink definitions, generated by tools/fetch_mavlink_xml.py.\n")
        f.write("     Source: https://github.com/mavlink/mavlink/tree/%s/message_definitions/v1.0\n" % COMMIT)
        f.write("     (common.xml, standard.xml, minimal.xml; MIT-licensed MAVLink definitions).\n")
        f.write("     Messages: %s\n     Enums: %s -->\n" % (", ".join(MESSAGES), ", ".join(ENUMS)))
        f.write(ET.tostring(out, encoding="unicode"))
        f.write("\n")
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
